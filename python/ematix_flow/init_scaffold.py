"""``flow init <path>`` — scaffold a new ematix-flow project.

Maven-archetype-style: drops a small, working pipeline + connection
config + Docker + systemd unit into the given directory so a new
user can `flow run` immediately. Lowers time-to-first-pipeline.

The scaffold deliberately includes only files that need to exist
before the first run; users add their own structure on top. No
opinionated package layout, no preconfigured CI — just enough to be
runnable.
"""
