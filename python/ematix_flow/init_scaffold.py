def scaffold_project(target_dir: Path, *, force: bool = False) -> list[Path]:
    """Create a starter project at ``target_dir``. Returns the list of
    files written. Raises :class:`FileExistsError` if files would be
    overwritten and ``force=False``."""
    target_dir.mkdir(parents=True, exist_ok=True)

    files = {
        "pipelines.py": _PIPELINES_PY,
        "connections.toml": _CONNECTIONS_TOML,
        "Dockerfile": _DOCKERFILE,
        "flow.service": _FLOW_SERVICE,
        ".gitignore": _GITIGNORE,
        "README.md": _README,
    }

    written: list[Path] = []
    for relpath, contents in files.items():
        out = target_dir / relpath
        if out.exists() and not force:
            raise FileExistsError(
                f"{out} already exists; pass --force to overwrite, or "
                f"choose a different target directory"
            )
        out.write_text(contents)
        written.append(out)
    return written
